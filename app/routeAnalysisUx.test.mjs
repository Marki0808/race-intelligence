import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { focusCompletedRouteAnalysis } from "./routeAnalysisFocus.ts";

function createHeading() {
  const calls = [];
  return {
    calls,
    focus: (options) => calls.push(["focus", options]),
    scrollIntoView: (options) => calls.push(["scroll", options]),
  };
}

test("successful analysis focuses the heading without implicit scrolling, then reveals it with motion preference", () => {
  const heading = createHeading();
  assert.equal(focusCompletedRouteAnalysis(true, heading, false), true);
  assert.deepEqual(heading.calls, [
    ["focus", { preventScroll: true }],
    ["scroll", { behavior: "smooth", block: "start" }],
  ]);

  const reducedMotionHeading = createHeading();
  assert.equal(focusCompletedRouteAnalysis(true, reducedMotionHeading, true), true);
  assert.deepEqual(reducedMotionHeading.calls, [
    ["focus", { preventScroll: true }],
    ["scroll", { behavior: "instant", block: "start" }],
  ]);
});

test("failed analysis or a missing heading does not move focus or scroll", () => {
  const heading = createHeading();
  assert.equal(focusCompletedRouteAnalysis(false, heading, false), false);
  assert.equal(focusCompletedRouteAnalysis(true, null, false), false);
  assert.deepEqual(heading.calls, []);
});

test("Route Mode schedules the transition only when analysis becomes available", async () => {
  const source = await readFile(new URL("./RouteMode.tsx", import.meta.url), "utf8");
  assert.match(source, /useEffect\(\(\) => \{\s*if \(!analysis\) return;[\s\S]*?focusCompletedRouteAnalysis\(Boolean\(analysis\), analysisHeadingRef\.current, prefersReducedMotion\);[\s\S]*?\}, \[analysis\]\);/);
  assert.match(source, /window\.matchMedia\("\(prefers-reduced-motion: reduce\)"\)/);
  assert.match(source, /analysisHeadingRef=\{analysisHeadingRef\}/);
});

test("loading and error feedback use accessible live status semantics", async () => {
  const source = await readFile(new URL("./RouteMode.tsx", import.meta.url), "utf8");
  assert.match(source, /role="status" aria-live="polite" aria-atomic="true"[\s\S]*?Reading your GPX and analyzing the route/);
  assert.match(source, /role="alert"[\s\S]*?\{error\}/);
});

test("application metadata describes Race Intelligence GPX route analysis", async () => {
  const source = await readFile(new URL("./layout.tsx", import.meta.url), "utf8");
  assert.match(source, /title: "Race Intelligence \| GPX Route Analysis"/);
  assert.match(source, /description: "Understand a trail route from its GPX[^"]*"/);
  assert.doesNotMatch(source, /Create Next App|Generated by create next app/);
});
